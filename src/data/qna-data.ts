export const getQnaStats = () => {
  const total = qnaDatabase.length
  const categories = Array.from(new Set(qnaDatabase.map(q => q.category)))
  
  return {
    total,
    categories,
    categoryStats: categories.map(cat => ({
      category: cat,
      count: qnaDatabase.filter(q => q.category === cat).length
    }))
  }
}

export const searchQna = (query: string): QnaItem[] => {
  const lowerQuery = query.toLowerCase()
  return qnaDatabase.filter(qna => 
    qna.question.toLowerCase().includes(lowerQuery) ||
    qna.answer.toLowerCase().includes(lowerQuery) ||
    qna.tags.some(tag => tag.toLowerCase().includes(lowerQuery))
  )
}

export const getQnaByCategory = (category: string): QnaItem[] => {
  return qnaDatabase.filter(qna => qna.category === category)
}

export const getRelatedQna = (qna: QnaItem): QnaItem[] => {
  if (!qna.relatedTopics) return []
  return qnaDatabase.filter(item => 
    item.id !== qna.id && 
    item.tags.some(tag => qna.relatedTopics?.includes(tag))
  ).slice(0, 3)
}
